const dishes = []
let sort = 200
for (const categoryId of Object.keys(DATA)) {
  const color = CATEGORY_STYLE[categoryId].color
  for (const row of DATA[categoryId]) {
    const [name, desc, price, mealsText, tagsText, spicyText, recipeText] =
      row
    const meals = mealsText
      .split('')
      .map(ch => MEAL_MAP[ch])
      .filter(Boolean)
    const tags = tagsText ? tagsText.split(',') : []
    let spicyLevels = []
    if (spicyText) {
      spicyLevels = ['不辣'].concat(spicyText.split(','))
    }
    const recipe = recipeText.split('|').join(nl)
    dishes.push({
      name,
      desc,
      price,
      categoryId,
      tags,
      spicyLevels,
      addons: [],
      color,
      meals,
      status: 'on',
      stock: -1,
      isRecommended: false,
      recipe,
      sort: sort++
    })
  }
}

const content =
  "import type { DishInput } from '../services/types'\n\n" +
  '// 家常菜模板扩展包（由 scripts/generate-dish-bank.js 生成）\n' +
  'export const DISH_BANK: DishInput[] = ' +
  JSON.stringify(
    dishes.map(dish => {
      const copy = Object.assign({}, dish)
      delete copy.sort
      return copy
    }),
    null,
    2
  ) +
  '\n'

fs.writeFileSync(
  path.join(__dirname, '..', 'miniprogram', 'utils', 'dish-bank.ts'),
  content
)
